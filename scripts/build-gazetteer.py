#!/usr/bin/env python3
"""Generate location-gazetteer.js (countries, cities, regions) from geonamescache.

Dev-only (scripts/ is excluded from the packaged zip). Re-run to refresh the data:

    python3 -m venv /tmp/geo && /tmp/geo/bin/pip install geonamescache
    /tmp/geo/bin/python scripts/build-gazetteer.py

Same source as ATS-market-reporter/req.py, trimmed so the extension stays small:
every city with population >= 100k, plus Indian cities >= 50k (NIQ India hiring).
"""
import json
import unicodedata
from pathlib import Path

import geonamescache

MIN_POP = 100_000
MIN_POP_BY_COUNTRY = {"IN": 50_000}

# Old/alternate names recruiters actually see on resumes, mapped to the geonames
# name. geonames' own alternatenames are not used: they are mostly
# transliterations ("ka ting", "sam zan") that would match ordinary words.
CURATED_ALIASES = {
    "bangalore": ("Bengaluru", "IN"),
    "bombay": ("Mumbai", "IN"),
    "madras": ("Chennai", "IN"),
    "calcutta": ("Kolkata", "IN"),
    "gurgaon": ("Gurugram", "IN"),
    "gurugram": ("Gurugram", "IN"),
    "allahabad": ("Prayagraj", "IN"),
    "mysore": ("Mysuru", "IN"),
    "trivandrum": ("Thiruvananthapuram", "IN"),
    "cochin": ("Kochi", "IN"),
    "vizag": ("Visakhapatnam", "IN"),
    "pondicherry": ("Puducherry", "IN"),
    "baroda": ("Vadodara", "IN"),
    "poona": ("Pune", "IN"),
    "navi mumbai": ("Navi Mumbai", "IN"),
    "peking": ("Beijing", "CN"),
    "saigon": ("Ho Chi Minh City", "VN"),
}

COUNTRY_ALIASES = {
    "uk": "GB", "u.k": "GB", "great britain": "GB", "england": "GB", "scotland": "GB", "wales": "GB",
    "usa": "US", "u.s": "US", "u.s.a": "US", "united states of america": "US", "america": "US",
    "uae": "AE", "u.a.e": "AE", "bharat": "IN",
    "czech republic": "CZ", "russia": "RU", "south korea": "KR", "viet nam": "VN",
    "holland": "NL", "the netherlands": "NL",
}

INDIAN_STATES = [
    "Andhra Pradesh", "Arunachal Pradesh", "Assam", "Bihar", "Chhattisgarh", "Goa", "Gujarat",
    "Haryana", "Himachal Pradesh", "Jharkhand", "Karnataka", "Kerala", "Madhya Pradesh",
    "Maharashtra", "Manipur", "Meghalaya", "Mizoram", "Nagaland", "Odisha", "Punjab", "Rajasthan",
    "Sikkim", "Tamil Nadu", "Telangana", "Tripura", "Uttar Pradesh", "Uttarakhand", "West Bengal",
    "Andaman and Nicobar", "Chandigarh", "Dadra and Nagar Haveli", "Daman and Diu", "Delhi",
    "Jammu and Kashmir", "Ladakh", "Lakshadweep", "Puducherry", "NCR",
]


def ascii_lower(s):
    return unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode("ascii").lower().strip()


def main():
    gc = geonamescache.GeonamesCache()
    countries = sorted(gc.get_countries().values(), key=lambda c: c["iso"])

    cities = []
    for c in gc.get_cities().values():
        pop = int(c.get("population") or 0)
        if pop < MIN_POP_BY_COUNTRY.get(c["countrycode"], MIN_POP):
            continue
        name = c["name"]
        if not ascii_lower(name):
            continue
        cities.append([name, c["countrycode"], round(pop / 1000)])
    cities.sort(key=lambda r: (-r[2], r[0]))

    # Keep curated targets that geonames lacks at this population cut (e.g. Navi Mumbai).
    have = {(ascii_lower(r[0]), r[1]) for r in cities}
    for alias, (target, iso) in CURATED_ALIASES.items():
        if (ascii_lower(target), iso) not in have:
            cities.append([target, iso, 0])
            have.add((ascii_lower(target), iso))

    data = {
        "countries": [[c["iso"], c["name"]] for c in countries],
        "countryAliases": COUNTRY_ALIASES,
        "cities": cities,
        "cityAliases": {k: list(v) for k, v in CURATED_ALIASES.items()},
        "regions": {
            "IN": INDIAN_STATES,
            "US": sorted(s["name"] for s in gc.get_us_states().values()),
        },
    }
    out = Path(__file__).resolve().parent.parent / "location-gazetteer.js"
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    # One city per line keeps diffs readable when the data is regenerated.
    body = body.replace('],["', '],\n["')
    out.write_text(
        "// location-gazetteer.js — GENERATED by scripts/build-gazetteer.py from geonamescache.\n"
        "// Do not edit by hand. Countries, cities (pop >= 100k; India >= 50k) and regions,\n"
        "// read by location-infer.js. Plain data: no candidate information.\n"
        "var SR_LOCATION_GAZETTEER = " + body + ";\n"
        'if (typeof module !== "undefined" && module.exports) module.exports = SR_LOCATION_GAZETTEER;\n',
        encoding="utf-8",
    )
    print(f"{out.name}: {len(data['countries'])} countries, {len(cities)} cities, {out.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
